// H-9 — writes deploy/comms/hoy-templates.json from src/notifications/launchEmails.ts (the source).
// The Company OS setup recipe (lane CO-4) loads `records` as its message_template and automation blocks; the rest is
// the hand-over: the Clerk email, the automations still blocked and why. `--check` fails when the file is stale.
import { build } from 'esbuild';
import { pathToFileURL } from 'node:url';
import { mkdtemp, rm, readFile, writeFile, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

export const OUT = 'deploy/comms/hoy-templates.json';
/** Rows of the recipe's first comms draft (CO-4, deploy/recipes/hoy.json) that these emails replace. */
export const RETIRED = { automation: ['receipt', 'hold_released', 'gift'], message_template: ['receipt', 'hold_released', 'gift'] };

export async function loadLaunchEmails() {
  const scratch = await mkdtemp(join(tmpdir(), 'hoy-launch-emails-'));
  try {
    const file = join(scratch, 'launchEmails.mjs');
    await build({ entryPoints: ['src/notifications/launchEmails.ts'], bundle: true, platform: 'node', format: 'esm', outfile: file, logLevel: 'silent' });
    return await import(pathToFileURL(file));
  } finally { await rm(scratch, { recursive: true, force: true }); }
}

export function templatesJson(m) {
  const brand = m.launchBrand();
  const cos = m.LAUNCH_EMAILS.filter((e) => e.sender === 'company_os');
  const clean = ({ _note, ...a }, template) => ({ ...(_note ? { _note } : {}), ...a, template, active: true });
  const doc = {
    _about: 'Hoy launch emails (NT-02, NT-03) for Company OS comms 1.5.0. Generated by `node scripts/gen-launch-emails.mjs` from src/notifications/launchEmails.ts in imagine-os/hoy: edit the source, not this file. `records` replaces the recipe\'s message_template and automation blocks; also merge `settings` and apply `retire`.',
    version: 1,
    requires: { comms: '1.5.0', bookings: '1.4.0', payments: '2.6.0', credits: '1.1.0', files: '1.1.0' },
    settings: {
      _note: 'MERGE these into the recipe\'s module settings: without them booking.hold_frozen, booking.hold_resumed and booking.moved are never written and three emails never send. reschedule_hours goes on together with policy_as_of_booking (ADR 0039). link_base_url is the app address behind {{links.base}}. email_from, and email_reply_to when it is set (the contact email, H-8), must be on a domain in MESSAGING_EMAIL_ALLOWED_DOMAINS. Dates render in the recipient person\'s locale: Hoy writes person.locale es (or none) so dates stay Spanish.',
      comms: { default_locale: 'es', link_base_url: { $var: 'app_url' }, email_from: { $var: 'email_from' } },
      bookings: { hold_frozen_while_payment_pending: true, reschedule_hours: 12, policy_as_of_booking: true },
      payments: { payment_document: 'receipt' },
    },
    brand: { ...brand, _pending: 'J5: brand and domain are pending with Jas. Change src/tenant/tenant.ts and regenerate.' },
    templates: m.LAUNCH_EMAILS.map((e) => ({
      key: e.key, row: e.row, name: e.name.es, sender: e.sender, trigger: e.trigger.es,
      automations: e.automations.map((a) => a.name),
      ...(e.blocked ? { blocked: e.blocked.automations.map((a) => a.name), blockers: e.blocked.blockers.map(({ gap, needs }) => ({ gap, needs })) } : {}),
    })),
    records: [
      { entity: 'message_template', key: ['key', 'channel', 'locale'],
        rows: cos.map((e) => ({ key: e.key, channel: 'email', locale: '', subject: m.fillBrand(e.subject, brand), body: m.fillBrand(e.body, brand), active: true })) },
      { entity: 'automation', key: ['name'], afterEnable: true, _note: 'After enable: an active email automation needs delivery on.',
        rows: cos.flatMap((e) => e.automations.map((a) => clean(a, e.key))) },
    ],
    retire: {
      _note: 'The recipe\'s placeholder rows these replace. apply-recipe only upserts, so on a tenant where the old recipe already ran, set active: false on these automations FIRST, then on these templates (a template an active automation uses can\'t be deactivated: template_missing). Otherwise every approval, release and gift sends twice. welcome keeps its key and name and is overwritten in place.',
      automation: RETIRED.automation, message_template: RETIRED.message_template,
    },
    blocked_automations: cos.flatMap((e) => (e.blocked?.automations ?? []).map((a) => ({ ...clean(a, e.key), active: false }))),
    clerk: m.LAUNCH_EMAILS.filter((e) => e.sender === 'clerk').map((e) => ({
      key: e.key, _note: 'Clerk sends the sign-in code. Set this copy in the Clerk dashboard (Customization → Emails → Verification code), Spanish, on the production instance.',
      subject: m.fillBrand(e.subject, brand), body: m.fillBrand(e.body, brand),
    })),
  };
  return JSON.stringify(doc, null, 2) + '\n';
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const next = templatesJson(await loadLaunchEmails());
  if (process.argv.includes('--check')) {
    const now = await readFile(OUT, 'utf8').catch(() => '');
    if (now !== next) { console.error(`${OUT} is stale: run node scripts/gen-launch-emails.mjs`); process.exit(1); }
    console.log(`${OUT} is current`);
  } else {
    await mkdir('deploy/comms', { recursive: true });
    await writeFile(OUT, next);
    console.log(`wrote ${OUT}`);
  }
}
