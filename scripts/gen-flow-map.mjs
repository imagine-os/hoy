// Regenerates the route tables of docs/flow-map.md from docs/screenshots/routes.json (the manifest the
// last screenshot pass read from window.__hoyos.routes). Every routed code gets one row per surface
// section — code, EN / ES name, purpose, route link(s) — so the map cannot drift from the app again.
// The hand-written "## Dependencies" section at the end of the file is kept verbatim.
// Usage: npm run flow-map   (after `npm run screenshots` or `-- --smoke`, which write routes.json)
import { readFileSync, writeFileSync } from 'node:fs';

const MANIFEST = new URL('../docs/screenshots/routes.json', import.meta.url);
const OUT = new URL('../docs/flow-map.md', import.meta.url);
const version = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8')).version;

let routes;
try { routes = JSON.parse(readFileSync(MANIFEST, 'utf8')); } catch { console.error('docs/screenshots/routes.json missing — run `npm run screenshots -- --smoke` first'); process.exit(1); }

/** Sections in reading order: which surface(s) feed them and, for the customer app, which code families. */
const SECTIONS = [
  { title: 'Testing hub', pick: (r) => r.code === 'HUB-01' },
  { title: 'Website (Sitio web)', pick: (r) => r.surface === 'public' && r.code !== 'HUB-01' && !/^A-0[1-5]|^C-21|^E-0/.test(r.code) },
  { title: 'Onboarding & authentication (Registro y autenticación)', pick: (r) => /^A-0[1-5]$|^C-21$|^E-04$/.test(r.code) },
  { title: 'Customer app (App de clientes)', pick: (r) => r.surface === 'customer' && !/^A-0[1-5]$|^C-21$|^E-0/.test(r.code) },
  { title: 'Customer — states and edges (Estados y bordes)', pick: (r) => /^E-0[1-3]$|^E-05$/.test(r.code) },
  { title: 'Teacher app (App de profesores)', pick: (r) => r.surface === 'teacher' },
  { title: 'Staff (Staff y recepción)', pick: (r) => r.surface === 'staff' },
  { title: 'Admin (Administración)', pick: (r) => r.surface === 'admin' },
  { title: 'Design system & developer tooling', pick: (r) => r.surface === 'dev' },
  { title: 'Operations manual & documentation', pick: (r) => r.surface === 'docs' },
];

const link = (path) => `[\`${path}\`](#${path})`;
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const codeKey = (c) => c.replace(/(\d+)/, (n) => n.padStart(3, '0'));

const seen = new Set();
const sections = SECTIONS.map((sec) => {
  const rows = new Map();
  for (const r of routes) {
    if (seen.has(r.path) || !sec.pick(r)) continue;
    seen.add(r.path);
    const row = rows.get(r.code) ?? { code: r.code, name: `${r.spec.name.en} · ${r.spec.name.es}`, purpose: r.spec.purpose.en, paths: [] };
    row.paths.push(r.path);
    rows.set(r.code, row);
  }
  return { ...sec, rows: [...rows.values()].sort((a, b) => codeKey(a.code).localeCompare(codeKey(b.code))) };
}).filter((s) => s.rows.length);
const missed = routes.filter((r) => !seen.has(r.path));
if (missed.length) { console.error('routes without a section:', missed.map((r) => `${r.code} ${r.path}`).join(', ')); process.exit(1); }

const existing = readFileSync(OUT, 'utf8');
const depsAt = existing.indexOf('\n## Dependencies');
const deps = depsAt >= 0 ? existing.slice(depsAt + 1) : '## Dependencies\n\n_(hand-written)_\n';

const codes = new Set(routes.map((r) => r.code)).size;
const head = `# HoyOS flow map (canvas v1.5 codes, routes from \`routes.json\`, v${version})

Codes are the canvas artboard ids; the **Route** column links to the screen in this app (hash routes, live when read at \`/#/docs/flow-map\`). Built vs stub status per code is at \`/#/dev/specs\`. **${routes.length} routes, ${codes} codes**, every one of them routed. Source of truth for prices is \`src/tenant/pricing.ts\` (Modelo de Valor v3); for policies, M-08 (\`/#/admin/settings\`). The tables below are generated by \`npm run flow-map\` from \`docs/screenshots/routes.json\` (each route's real spec, published by the app on \`window.__hoyos.routes\`); the **Dependencies** section is hand-written.

Names are the spec names (EN · ES); a code with several routes (M-03, K-03, A-06, C-08 / C-08b…) lists them all. M-08 is a family: M-08a…M-08f are its routed sub-pages (\`docs/pages/M-08.md\`); policies such as the cancellation window are read from M-08a, not written here.
`;

const body = sections.map((s) => [`## ${s.title}`, '', '| Code | EN · ES | Purpose | Route |', '|------|---------|---------|-------|', ...s.rows.map((r) => `| ${r.code} | ${cell(r.name)} | ${cell(r.purpose)} | ${r.paths.map(link).join(' · ')} |`), ''].join('\n')).join('\n');

writeFileSync(OUT, `${head}\n${body}\n${deps}`);
console.log(`wrote docs/flow-map.md — ${routes.length} routes, ${codes} codes, ${sections.length} sections`);
