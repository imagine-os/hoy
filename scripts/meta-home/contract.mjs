import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
import { createHash } from 'node:crypto';
import { createPilotGate, pilotFrame } from '../../server/metaHomePilot.mjs';

const key = 'a'.repeat(43);
const form = Buffer.from('key=' + key);
const digest = createHash('sha256').update(key).digest('hex');
const conf = { environment: 'production', metaHomePilot: {digest} };
const request = { method: 'POST', headers: { host: 'hoyhumanclub.com', origin:'https://hoyhumanclub.com',
  'content-type':'application/x-www-form-urlencoded','sec-fetch-dest':'iframe','sec-fetch-site':'same-origin' } };
let now = 1_000_000;
const gate = createPilotGate(conf,()=>now);
assert.equal(Boolean(gate.available(request)),true);
for (const c of [{}, {...conf, metaHomePilot:null}, {...conf, environment:'test'}, {...conf, testGate:{on:true}}]) assert.equal(Boolean(createPilotGate(c).available(request)),false);
for (const h of [{host:'other.invalid'},{origin:'null'},{'sec-fetch-dest':'document'},{'sec-fetch-site':'cross-site'},{'content-type':'text/plain'}]) assert.equal(await gate.claim({...request,headers:{...request.headers,...h}},'',async()=>form),null);
assert.equal(await gate.claim(request,'?data=private',async()=>form),null);
assert.equal(await gate.claim({...request,method:'GET'},'',async()=>form),null);
assert.equal(await gate.claim(request,'',async()=>Buffer.from('key='+'b'.repeat(43))),null);
assert.equal(await gate.claim(request,'',async()=> 'too_large'),null);
const claims=await Promise.all([gate.claim(request,'',async()=>form),gate.claim(request,'',async()=>form)]);
assert.equal(claims.filter(Boolean).length,1);
assert.equal(gate.available(request),false);
const expired=createPilotGate(conf,()=>now);
now+=15*60*1000;
assert.equal(await expired.claim(request,'',async()=>form),null);
const result = pilotFrame();
assert.equal(result.headers['Referrer-Policy'],'no-referrer');
assert.equal(result.headers['Cache-Control'],'no-store');
assert.match(result.headers['Content-Security-Policy'],/frame-ancestors 'self'; sandbox allow-scripts/);
assert.doesNotMatch(result.headers['Content-Security-Policy'],/unsafe-inline|allow-same-origin/);
const source = result.body.match(/<script>([\s\S]+)<\/script>/)[1];
assert.ok(result.headers['Content-Security-Policy'].includes('sha256-'+createHash('sha256').update(source).digest('base64')));
function boot({ child=true, origin='null', referrer='', search='', hash='' }={}) {
  const loads = [];
  const window = { origin, location: {search, hash} };
  window.parent = child ? {} : window;
  const document = {referrer, createElement:()=>({}), head:{append:s=>loads.push(s)}};
  vm.runInNewContext(source,{window,document});
  return {calls: Array.from(window.fbq?.queue ?? [], args => Array.from(args)),loads};
}
const go = boot();
assert.deepEqual(go.calls,[['set','autoConfig',false,'963759066544104'],['init','963759066544104'],['trackSingle','963759066544104','PageView']]);
assert.equal(go.loads.length,1);
assert.equal(go.loads[0].src,'https://connect.facebook.net/en_US/fbevents.js');
for(const options of [{child:false},{origin:'https://hoyhumanclub.com'},{referrer:'https://hoyhumanclub.com/'},{search:'?x=1'},{hash:'#private'}]) assert.deepEqual(boot(options),{calls:[],loads:[]});
