import assert from 'node:assert/strict';
import { build } from 'esbuild';
const {outputFiles}=await build({stdin:{contents:`export {updateCoachOps, createCoachOps, coachEmailProblem} from './src/modules/classSchedule/live/scheduleOps';`,resolveDir:process.cwd()},write:false,bundle:true,platform:'node',format:'esm'});
const {updateCoachOps,createCoachOps,coachEmailProblem}=await import('data:text/javascript;base64,'+Buffer.from(outputFiles[0].contents).toString('base64'));
const d={name:'Fictional Instructor',active:true};
const old='previous@example.test', newer='next@example.test';
const person=draft=>updateCoachOps('test-coach','test-person',{...d,...draft})[0];
assert.deepEqual(person({email:' Next@EXAMPLE.test ',emailAtOpen:old}),{op:'update',entity:'person',id:'test-person',ifMatch:{field:'email',value:old},data:{name:d.name,email:newer}});
assert.deepEqual(person({email:newer,emailAtOpen:null}).ifMatch,{field:'email',value:null});
const missing=JSON.parse(JSON.stringify(person({email:newer})));
assert.deepEqual(missing.ifMatch,{field:'email'});
assert.equal(missing.data.email,newer);
assert(!('email' in person({email:' Previous@EXAMPLE.TEST ',emailAtOpen:old}).data));
assert(!('email' in person({phone:'123'}).data));
assert.throws(()=>person({email:'typo',emailAtOpen:old}),/invalid_email/);
assert.throws(()=>person({email:'',emailAtOpen:old}),/empty_email/);
assert(!('email' in person({email:'',emailAtOpen:null}).data));
assert.equal(coachEmailProblem('invalid',undefined),'invalid_email');
assert.equal(coachEmailProblem('',old),'empty_email');
assert.equal(coachEmailProblem('',undefined),null);
assert.equal(createCoachOps({...d,email:' New@EXAMPLE.test '})[0].data.email,'new@example.test');
assert(!('email' in createCoachOps(d)[1].data));
console.log('PASS teacher profile email draft: normalized identity-safe patch, explicit previous-value CAS, no unchanged writes, validation');
