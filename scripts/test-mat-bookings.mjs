import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
const scratch = await mkdtemp(join(tmpdir(), 'hoy-mats-'));
try {
  const file = join(scratch, 'provider.mjs');
  await build({ entryPoints: ['src/data/MockProvider.ts'], bundle: true, platform: 'node', format: 'esm', outfile: file, define: { 'import.meta.env.BASE_URL': '"/"' } });
  const stored = new Map();
  globalThis.localStorage = { getItem: k => stored.get(k) ?? null, setItem: (k, v) => stored.set(k, v) };
  const { MockProvider } = await import(pathToFileURL(file));
  const db = new MockProvider();
  const seed = await db.list('class_sessions');
  assert(seed.some(s => new Date(s.starts_at) - Date.now() > 30 * 86400000), 'demo horizon exceeds one month');
  const session = await db.insert('class_sessions', { modality_id: 'mod_ligereza', teacher_id: 'tea_sara_c', room_id: 'room_main', starts_at: new Date(Date.now() + 86400000).toISOString(), ends_at: new Date(Date.now() + 90000000).toISOString(), capacity: 16, booked_count: 0, status: 'scheduled', title: 'Mat transaction test' });
  const row = (user, mat) => ({ user_id: user, session_id: session.id, status: 'booked', paid_with: 'package', mat_number: mat });
  const a = await db.insert('bookings', row('test-a', 16));
  assert.equal(a.mat_number, 16);
  await assert.rejects(db.insert('bookings', row('test-b', 16)), /mat_taken/);
  await assert.rejects(db.insert('bookings', row('test-a', 15)), /booking_exists/);
  for (const n of [0, 17, 1.5]) await assert.rejects(db.insert('bookings', row('test-b', n)), /mat_invalid/);
  const races = await Promise.allSettled([db.insert('bookings', row('test-b', 8)), db.insert('bookings', row('test-c', 8))]);
  assert.equal(races.filter(r => r.status === 'fulfilled').length, 1, 'one same-provider claimant succeeds');
  assert.equal((await db.get('class_sessions', session.id)).booked_count, 2);
  await db.update('bookings', a.id, { status: 'cancelled' });
  assert.equal((await db.get('class_sessions', session.id)).booked_count, 1);
  const b = await db.insert('bookings', row('test-d', 16));
  assert.equal(b.mat_number, 16, 'cancellation frees the same mat');
  const reloaded = new MockProvider();
  assert.equal((await reloaded.get('bookings', b.id)).mat_number, 16, 'selection survives reload');
  await assert.rejects(db.update('bookings', b.id, { mat_number: 8 }), /mat_taken/);
  for (let n = 0; n < 14; n++) await db.insert('bookings', row(`fill-${n}`, null));
  await assert.rejects(db.insert('bookings', row('overflow', null)), /session_full/);
  assert.equal((await db.get('class_sessions', session.id)).booked_count, 16);
  const before = JSON.parse(stored.get('hoyos.db.v1'));
  before.version = 2;
  before.db.media_assets[0].url = 'https://example.org/preserved-photo.webp';
  stored.set('hoyos.db.v1', JSON.stringify(before));
  const migrated = new MockProvider();
  assert.equal((await migrated.list('media_assets'))[0].url, 'https://example.org/preserved-photo.webp', 'same-day CMS data survives v2 migration');
  assert.equal((await migrated.get('bookings', b.id)).mat_number, 16);
  console.log('PASS: 16 mats, bounds, duplicate booking, concurrent collision, cancellation release, persistence, capacity, full state, 42-day horizon and CMS-preserving migration.');
} finally { await rm(scratch, { recursive: true, force: true }); }
