#!/usr/bin/env node
/* ============================================================================
   Generate Postgres DDL and Row Level Security policies from src/data/schema.js.

     node tools/gen-supabase.mjs > supabase/migrations/0001_init.sql

   WHY THIS EXISTS: the schema is already declared once, in JavaScript, with
   every column's type, its foreign key, whether it holds personal data, and
   which permissions may read or write the table. Hand-writing the SQL would
   create a second source of truth that drifts from the first within a week.

   WHAT IT EMITS
     · one CREATE TABLE per entry, with FKs and sensible defaults
     · `updated_at` triggers where the table declares the column
     · RLS enabled on every table, with policies derived from `read`/`write`
     · tenant isolation on every table carrying `tenantKey: true`
     · append-only tables get INSERT but no UPDATE or DELETE policy
     · a `has_permission()` helper that resolves the role → permission model

   WHAT IT DOES NOT DO — deliberately, because these need a human decision:
     · indexes beyond primary and foreign keys (depends on real query patterns)
     · data migration from the seed
     · Supabase Storage buckets
   ========================================================================= */

import { TABLES, TYPES, DOMAINS } from '../src/data/schema.js';
import { ROLES, ROLE_ORDER, permissionsOf, PERMISSIONS } from '../src/core/roles.js';

const out = [];
const w = (...lines) => out.push(...lines);

/* ---- Preamble -------------------------------------------------------------- */

w(`-- =============================================================================
-- HOY OS — initial schema
-- GENERATED by tools/gen-supabase.mjs from src/data/schema.js and
-- src/core/roles.js. Do not edit this file; edit those and regenerate.
-- Generated: ${new Date().toISOString()}
-- =============================================================================

create extension if not exists "pgcrypto";
create extension if not exists "citext";

-- Supabase provides the authenticated role and auth.uid(). Creating them when absent
-- makes this migration apply — and therefore be testable — against a plain
-- Postgres as well. On Supabase both already exist and these are no-ops.
do $$ begin
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then
    create role authenticated nologin;
  end if;
end $$;

create schema if not exists auth;
do $$ begin
  if not exists (
    select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
     where n.nspname = 'auth' and p.proname = 'uid'
  ) then
    execute 'create function auth.uid() returns uuid language sql stable as $f$ select null::uuid $f$';
  end if;
end $$;

-- updated_at maintenance, applied by trigger to every table that declares it.
create or replace function public.touch_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;
`);

/* ---- The role → permission model, as data ---------------------------------
   Emitted AFTER the tables, because the helper functions below are `language
   sql` and Postgres validates their bodies at creation time — declaring
   current_role_name() before public.profiles exists fails outright.
   -------------------------------------------------------------------------- */

const foreignKeys = [];
const helpers = [];
const hw = (...lines) => helpers.push(...lines);

hw(`-- -----------------------------------------------------------------------------
-- Roles and permissions
--
-- The matrix is generated from src/core/roles.js, including inheritance, so a
-- role that gains a permission in the app gains it in the database on the next
-- regeneration. A policy never names a role directly — it names a permission.
-- -----------------------------------------------------------------------------

create table if not exists public.role_permissions (
  role       text not null,
  permission text not null,
  primary key (role, permission)
);

truncate public.role_permissions;
insert into public.role_permissions (role, permission) values`);

const rows = [];
for (const role of ROLE_ORDER) {
  for (const p of [...permissionsOf(role)].sort()) rows.push(`  ('${role}', '${p}')`);
}
hw(rows.join(',\n') + ';\n');

hw(`-- The role of the calling user, read from their profile.
create or replace function public.current_role_name() returns text
language sql stable security definer set search_path = public as $$
  select role from public.profiles where user_id = auth.uid() limit 1;
$$;

-- The tenant of the calling user. Every tenant-scoped policy funnels through
-- this, which is what makes multi-tenancy a property of the database rather
-- than a discipline the application has to remember.
create or replace function public.current_tenant_id() returns uuid
language sql stable security definer set search_path = public as $$
  select tenant_id from public.profiles where user_id = auth.uid() limit 1;
$$;

create or replace function public.has_permission(perm text) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.role_permissions
    where role = public.current_role_name() and permission = perm
  );
$$;

-- The profile id of the calling user, for "their own row" policies.
create or replace function public.current_profile_id() returns uuid
language sql stable security definer set search_path = public as $$
  select id from public.profiles where user_id = auth.uid() limit 1;
$$;

-- role_permissions lives in the public schema, so Supabase exposes it through
-- PostgREST like any other table. It is not secret — it is the same matrix the
-- client already ships in roles.js — but it must never be writable from a
-- client, or a student could grant themselves 'tables:write'. Readable to
-- signed-in users, written only by the service role (which bypasses RLS).
alter table public.role_permissions enable row level security;
drop policy if exists role_permissions_select on public.role_permissions;
create policy role_permissions_select on public.role_permissions
  for select to authenticated using (true);
`);

/* ---- Tables ---------------------------------------------------------------- */

/* Postgres reserves `group`, `role`, `order`, `references` and others that are
   perfectly reasonable column names. Quoting every identifier is cheaper than
   maintaining a reserved-word list that will be wrong the next time one is added. */
const q = (name) => `"${name}"`;

const sqlType = (col) => {
  const base = TYPES[col.type]?.sql || 'text';
  return col.pk ? 'uuid primary key default gen_random_uuid()' : base;
};

const defaultClause = (col) => {
  if (col.pk) return '';
  if (col.default === 'now()') return ' default now()';
  if (typeof col.default === 'boolean') return ` default ${col.default}`;
  if (typeof col.default === 'number') return ` default ${col.default}`;
  if (typeof col.default === 'string') return ` default '${col.default.replace(/'/g, "''")}'`;
  return '';
};

for (const table of TABLES) {
  const domain = DOMAINS[table.domain]?.label.en || table.domain;
  w(`-- -----------------------------------------------------------------------------
-- ${table.name}  ·  ${domain}
-- ${table.purpose.en}
-- -----------------------------------------------------------------------------
create table if not exists public.${table.name} (`);

  const lines = [];
  for (const col of table.columns) {
    if (col.derived) continue;                    // computed in a view, not stored
    const bits = [`  ${q(col.name)}`, sqlType(col)];
    if (!col.pk) {
      bits.push(defaultClause(col).trim());
      if (col.unique) bits.push('unique');
    }
    const line = bits.filter(Boolean).join(' ');
    // Foreign keys are added in a second pass below, not inline: the tables
    // reference each other in both directions (consents → legal_documents,
    // bookings → credits → orders), so no single CREATE TABLE order satisfies
    // them all. Declaring the columns first and the constraints after makes
    // the order of src/data/schema.js irrelevant.
    const comments = [];
    if (col.pii) comments.push('PII · Ley 1581');
    if (col.secret) comments.push('secret — never select in the client');
    if (col.note) comments.push(col.note);
    if (col.values) comments.push(`one of: ${col.values.join(' | ')}`);
    // The comment must follow the comma, not precede it — a trailing `--`
    // swallows the separator and the next column joins the previous one.
    lines.push({ sql: line, comment: comments.join('; ') });
  }
  w(lines.map((l, i) =>
    l.sql + (i < lines.length - 1 ? ',' : '') + (l.comment ? `  -- ${l.comment}` : '')).join('\n'));
  w(');');

  // Enum-ish columns get a check constraint rather than a Postgres enum type,
  // because adding a value to an enum type requires a migration and these
  // vocabularies still move.
  for (const col of table.columns) {
    if (col.type !== 'enum' || !col.values) continue;
    w(`alter table public.${table.name} drop constraint if exists ${table.name}_${col.name}_check;`);
    w(`alter table public.${table.name} add constraint ${table.name}_${col.name}_check`);
    w(`  check (${q(col.name)} is null or ${q(col.name)} in (${col.values.map((v) => `'${v}'`).join(', ')}));`);
  }

  // Foreign key indexes — Postgres does not create these automatically and
  // their absence is the most common cause of a slow join.
  for (const col of table.columns.filter((c) => c.ref && !c.derived)) {
    const [refTable, refCol] = col.ref.split('.');
    // Deliberately no ON DELETE CASCADE: in a studio's records, deleting a
    // class must never silently delete the bookings that prove people paid.
    foreignKeys.push(
      `alter table public.${table.name} drop constraint if exists ${table.name}_${col.name}_fkey;`,
      `alter table public.${table.name} add constraint ${table.name}_${col.name}_fkey`,
      `  foreign key (${q(col.name)}) references public.${refTable}(${q(refCol)});`);
    w(`create index if not exists ${table.name}_${col.name}_idx on public.${table.name}(${q(col.name)});`);
  }

  if (table.columns.some((c) => c.name === 'updated_at')) {
    w(`drop trigger if exists ${table.name}_touch on public.${table.name};`);
    w(`create trigger ${table.name}_touch before update on public.${table.name}`);
    w(`  for each row execute function public.touch_updated_at();`);
  }
  w('');
}

w('-- ---------------------------------------------------------------------------',
  '-- Foreign keys, added after every table exists.',
  '-- ---------------------------------------------------------------------------',
  ...foreignKeys, '');

/* Helpers are emitted here: after every table exists, before the policies
   that call them. */
w(...helpers);

/* ---- Row Level Security ---------------------------------------------------- */

w(`-- =============================================================================
-- Row Level Security
--
-- Enabled on every table. A table with an empty \`read\` list in schema.js is
-- readable by any signed-in user of the tenant (the catalogue: classes, plans,
-- teachers). A table with permissions listed requires one of them.
-- =============================================================================
`);

for (const table of TABLES) {
  const t = table.name;
  const tenantScoped = table.columns.some((c) => c.tenantKey);
  const tenantClause = tenantScoped ? `tenant_id = public.current_tenant_id()` : 'true';
  const ownRow = table.columns.some((c) => c.name === 'profile_id');

  w(`-- ${t}`);
  w(`alter table public.${t} enable row level security;`);
  for (const suffix of ['select', 'insert', 'update', 'delete']) {
    w(`drop policy if exists ${t}_${suffix} on public.${t};`);
  }

  const readPerms = table.read || [];
  const readTest = readPerms.length
    ? `(${readPerms.map((p) => `public.has_permission('${p}')`).join(' or ')}${
        ownRow ? ` or profile_id = public.current_profile_id()` : ''})`
    : 'true';

  w(`create policy ${t}_select on public.${t} for select`);
  w(`  using (${tenantClause} and ${readTest});`);

  const writePerms = table.write || [];
  if (writePerms.length) {
    const writeTest = `(${writePerms.map((p) => `public.has_permission('${p}')`).join(' or ')}${
      ownRow ? ` or profile_id = public.current_profile_id()` : ''})`;

    w(`create policy ${t}_insert on public.${t} for insert`);
    w(`  with check (${tenantClause} and ${writeTest});`);

    if (table.appendOnly) {
      w(`-- ${t} is append-only: no update or delete policy exists, so both are`);
      w(`-- denied by RLS regardless of role. ${
        t === 'audit_log' || t === 'consents' ? 'Ley 1581 requires the record to be immutable.' : ''}`);
    } else {
      w(`create policy ${t}_update on public.${t} for update`);
      w(`  using (${tenantClause} and ${writeTest}) with check (${tenantClause});`);
      w(`create policy ${t}_delete on public.${t} for delete`);
      w(`  using (${tenantClause} and ${writeTest});`);
    }
  } else {
    w(`-- ${t} has no write permissions in schema.js: writes are service-role only.`);
  }
  w('');
}

/* ---- PII register ---------------------------------------------------------- */

w(`-- =============================================================================
-- Personal data register (Ley 1581 de 2012 / Decreto 1377 de 2013)
-- The columns below hold personal data. Reads of them are logged to audit_log
-- by the application; this comment block is the register itself, generated so
-- it cannot fall behind the schema.
-- =============================================================================`);

for (const table of TABLES) {
  const pii = table.columns.filter((c) => c.pii);
  if (pii.length) w(`--   ${table.name}: ${pii.map((c) => c.name).join(', ')}`);
}

w('');
console.log(out.join('\n'));
